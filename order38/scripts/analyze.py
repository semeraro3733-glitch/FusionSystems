#!/usr/bin/env python3
"""Analyse the Stage 1a output (data/stage1a/part_*.txt).

Each line:  id;status;reason            (reject)
            id;survive;[inv];[cands...];time
            id;error;...
A candidate is [order,index,type,elab,abelian,rank,|Aut(E)|].

Writes data/stage1a_survivors.txt (id;inv;cands sorted by difficulty) and
tables/stage1a_stats.tex, and prints a summary.
"""
import glob, re, sys, os, collections

if len(sys.argv) == 3 and sys.argv[1] == "--lastid":
    # the last id with a complete line in the given part file (for resuming)
    last = 0
    cur = ""
    with open(sys.argv[2]) as f:
        for line in f:
            line = line.rstrip("\n")
            if line.endswith("\\"):
                cur += line[:-1]; continue
            cur += line
            p = cur.split(";")
            if len(p) >= 3 and p[0].isdigit():
                last = int(p[0])
            cur = ""
    print(last)
    sys.exit(0)

base = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
def read_joined(fn):
    """Lines of fn, with GAP's wrapped lines (ending in a backslash) joined."""
    out = []
    cur = ""
    with open(fn) as f:
        for line in f:
            line = line.rstrip("\n")
            if line.endswith("\\"):
                cur += line[:-1]
                continue
            cur += line
            if cur.strip():
                out.append(cur)
            cur = ""
    return out

lines = []
for fn in sorted(glob.glob(os.path.join(base, "data", "stage1a", "part_*.txt"))):
    lines.extend(read_joined(fn))

n = len(lines)
status = collections.Counter()
reasons = collections.Counter()
times = []
errors = []
survivors = []
cand_re = re.compile(r"\[(\d+),(\d+),([^,\]]+),(true|false),(true|false),(\d+),(\d+)\]")
for line in lines:
    parts = line.split(";")
    if len(parts) < 2:
        continue
    try:
        gid = int(parts[0])
    except ValueError:
        continue
    st = parts[1]
    status[st] += 1
    try:
        times.append(int(parts[-1]))
    except ValueError:
        pass
    if st == "reject":
        reasons[parts[2]] += 1
    elif st == "error":
        errors.append(gid)
    elif st == "survive":
        inv = parts[2]
        cands = [(int(o), int(i), t, e == "true", a == "true", int(r), int(au)) for (o, i, t, e, a, r, au) in cand_re.findall(parts[3])]
        survivors.append((gid, inv, cands))

def difficulty(s):
    # largest elementary abelian candidate (by order), then largest abelian, then number of candidates
    gid, inv, cands = s
    el = max([c[0] for c in cands if c[3]], default=1)
    ab = max([c[0] for c in cands if c[4]], default=1)
    return (el, ab, len(cands), gid)

survivors.sort(key=difficulty)
with open(os.path.join(base, "data", "stage1a_survivors.txt"), "w") as f:
    for gid, inv, cands in survivors:
        f.write("%d;%s;%s\n" % (gid, inv, " ".join("[%d,%d,%s,%s,%s,%d,%d]" % (o, i, t, str(e).lower(), str(a).lower(), r, au) for (o, i, t, e, a, r, au) in cands)))

shape = collections.Counter()
for gid, inv, cands in survivors:
    shape[tuple(sorted(set((c[0], c[1], c[2], c[3]) for c in cands)))] += 1

print("groups processed: %d of 1396077 (%.2f %%)" % (n, 100.0 * n / 1396077))
print("status:", dict(status))
print("reasons:")
for r, c in reasons.most_common():
    print("   %7d  %s" % (c, r))
if times:
    print("time per group: mean %.0f ms, max %d ms, total %.1f h" % (sum(times) / len(times), max(times), sum(times) / 3.6e6))
print("errors:", errors[:20], "..." if len(errors) > 20 else "")
print("survivors: %d; by candidate shape (order,index,type,elab):" % len(survivors))
for sh, c in shape.most_common(30):
    print("   %6d  %s" % (c, list(sh)))

with open(os.path.join(base, "tables", "stage1a_stats.tex"), "w") as f:
    f.write("%% generated by analyze.py from %d groups\n" % n)
    f.write("\\begin{tabular}{lr}\n\\toprule\noutcome & groups\\\\\n\\midrule\n")
    f.write("processed & %d\\\\\n" % n)
    for r, c in reasons.most_common():
        f.write("rejected: %s & %d\\\\\n" % (r.replace("_", "\\_").replace("|S:Z(S)| <= 9", "$|S:\\Z(S)|\\le 9$"), c))
    f.write("errors & %d\\\\\n" % len(errors))
    f.write("survivors & %d\\\\\n" % len(survivors))
    f.write("\\bottomrule\n\\end{tabular}\n")
