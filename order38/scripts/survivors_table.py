#!/usr/bin/env python3
"""Tables of the Stage 1b survivors and their Stage 2 status for report.tex.

Writes tables/stage1b_stats.tex (outcomes of Stage 1b) and
tables/stage1b_survivors.tex (one row per survivor: invariants of S,
3'-part of |Aut(S)|, proto-essential candidates, Stage 2 status).
"""
import glob, os, re, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
KNOWN = {2221: r"$\PSL_3(163)$, $\PSU_3(647)$"}
SECTIONS = {2221: "sec:psl3", 2225: "sec:2225",
            2025: "sec:class6none", 2029: "sec:class6none", 2193: "sec:class6none", 2021: "sec:class6none", 2205: "sec:class6none",
            1111: "sec:tier81", 1115: "sec:tier81", 1167: "sec:tier81", 1176: "sec:tier81", 1225: "sec:tier81", 1229: "sec:tier81"}


def read_joined(fn):
    out, cur = [], ""
    for line in open(fn):
        line = line.rstrip("\n")
        if line.endswith("\\"):
            cur += line[:-1]
            continue
        cur += line
        out.append(cur)
        cur = ""
    if cur:
        out.append(cur)
    return out


def threeprime(n):
    while n % 3 == 0:
        n //= 3
    return n


def pow3(n):
    k = 0
    while n % 3 == 0:
        n //= 3
        k += 1
    return k


def main():
    # Stage 1a invariants of the survivors
    inv = {}
    for fn in glob.glob(os.path.join(ROOT, "data", "stage1a", "part_*.txt")):
        for line in read_joined(fn):
            parts = line.split(";")
            if len(parts) >= 4 and parts[1] == "survive":
                try:
                    gid = int(parts[0])
                except ValueError:
                    continue
                nums = [int(x) for x in re.findall(r"\d+", parts[2])]
                inv[gid] = nums
    # Stage 1b outcomes
    stats = collections.Counter()
    for line in read_joined(os.path.join(ROOT, "data", "stage1b.txt")):
        parts = line.split(";")
        if len(parts) < 3:
            continue
        if parts[1] == "survive":
            stats["survive"] += 1
        elif parts[1] == "reject":
            cands = [x for x in parts[2:] if "(R" in x]
            reason = cands[0] if cands else parts[3]
            reason = re.sub(r"\(R\d\)", "", reason).strip()
            stats["reject: " + reason] += 1
        else:
            stats[parts[1]] += 1
    # Stage 2 status
    stage2 = {}
    fn = os.path.join(ROOT, "data", "stage2.txt")
    if os.path.exists(fn):
        for line in read_joined(fn):
            parts = line.split(";")
            try:
                gid = int(parts[0])
            except ValueError:
                continue
            stage2[gid] = parts[1]
    running = set()
    for fn in glob.glob(os.path.join(ROOT, "logs", "stage2_*.log")):
        gid = int(re.findall(r"stage2_(\d+)\.log", fn)[0])
        s = open(fn).read()
        if "DONE" in s:
            m = re.search(r"# (\d+) fusion systems", s)
            if m and gid not in stage2:
                stage2[gid] = m.group(1)
        elif gid not in stage2:
            running.add(gid)
    # survivors
    rows = []
    for line in read_joined(os.path.join(ROOT, "data", "stage1b_survivors.txt")):
        parts = line.split(";")
        if len(parts) < 3:
            continue
        gid = int(parts[0]); aut = int(parts[1])
        protos = re.findall(r"\[(\d+),(\d+),(\w+),(\w+),(\d+),(\d+)\]", parts[2])
        # compact description: order^(count), e = elementary abelian
        cnt = collections.OrderedDict()
        for (o, i, e, a, r, n) in protos:
            key = (int(o), e == "true", int(i))
            cnt[key] = cnt.get(key, 0) + 1
        desc = []
        for (o, e, i), c in sorted(cnt.items(), key=lambda t: (-t[0][0], t[0][1])):
            d = "$3^{%d}%s$" % (pow3(o), "_{\\mathrm{e}}" if e else "")
            if i != 3:
                d += "($%d$)" % i
            if c > 1:
                d += r"$\times%d$" % c
            desc.append(d)
        elab = max([int(o) for (o, i, e, a, r, n) in protos if e == "true"] + [1])
        rows.append((elab, gid, aut, desc))
    rows.sort()
    with open(os.path.join(ROOT, "tables", "stage1b_stats.tex"), "w") as f:
        f.write("%% generated by survivors_table.py\n\\begin{tabular}{lr}\n\\toprule\noutcome of Stage 1b & groups\\\\\n\\midrule\n")
        f.write("processed & %d\\\\\n" % sum(stats.values()))
        for k, v in sorted(stats.items(), key=lambda t: -t[1]):
            if k == "survive":
                continue
            f.write("%s & %d\\\\\n" % (k.replace("|", "$|$").replace("O^3", "$O^3$").replace("[S,", "$[S,$").replace("]", "$]$").replace("_", r"\_"), v))
        f.write("survivors & %d\\\\\n\\bottomrule\n\\end{tabular}\n" % stats["survive"])
    with open(os.path.join(ROOT, "tables", "stage1b_survivors.tex"), "w") as f:
        f.write("%% generated by survivors_table.py\n{\\small\n\\begin{tabular}{rrrrrrlll}\n\\toprule\n")
        f.write("$n$ & $|\\Z(S)|$ & class & $d(S)$ & $\\exp S$ & $|\\Aut(S)|_{3'}$ & proto-essential candidates & Stage 2 & \\\\\n\\midrule\n")
        for elab, gid, aut, desc in rows:
            iv = inv.get(gid, [0, 0, 0, 0, 0, 0])
            if str(gid) in [str(x) for x in stage2] or gid in stage2:
                st = stage2[gid]
                st = ("%s system%s" % (st, "" if st == "1" else "s")) if st.isdigit() else st
            elif gid in running:
                st = "running"
            else:
                st = "pending"
            extra = []
            if gid in KNOWN:
                extra.append("Sylow of " + KNOWN[gid])
            if gid in SECTIONS:
                extra.append("Section~\\ref{%s}" % SECTIONS[gid])
            f.write("%d & %d & %d & %d & %d & %d & %s & %s & %s\\\\\n" % (
                gid, iv[0], iv[1], iv[2], iv[3], threeprime(aut), ", ".join(desc), st, "; ".join(extra)))
        f.write("\\bottomrule\n\\end{tabular}}\n")
    print("survivors:", len(rows), "stage2 done:", len(stage2), "running:", sorted(running))


if __name__ == "__main__":
    main()
